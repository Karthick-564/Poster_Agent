"""Connect to the native `vectorcraft-cli mcp` server as an MCP *client* and dump its tool list.

Usage: python scripts/list_vectorcraft_tools.py [--cli PATH] [--out docs/vectorcraft_tools.md]
"""
from __future__ import annotations

import argparse
import asyncio
import json
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CLI = ROOT / "tools/vectorcraft-0.21.0/vectorcraft-0.21.0-windows-x64-portable/vectorcraft-cli.exe"


async def list_tools(cli: Path) -> list[dict]:
    params = StdioServerParameters(
        command=str(cli),
        args=["mcp", "--headless",
              "--automation-read-root", str(ROOT), "--automation-write-root", str(ROOT)],
    )
    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            result = await session.list_tools()
            return [t.model_dump() for t in result.tools]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cli", type=Path, default=DEFAULT_CLI)
    ap.add_argument("--out", type=Path, default=ROOT / "docs/vectorcraft_tools.md")
    args = ap.parse_args()

    tools = asyncio.run(list_tools(args.cli))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# VectorCraft native MCP tools\n\nGenerated by `scripts/list_vectorcraft_tools.py` — {len(tools)} tools.\n"]
    for t in sorted(tools, key=lambda t: t["name"]):
        lines.append(f"## `{t['name']}`\n\n{t.get('description') or ''}\n")
        lines.append("```json\n" + json.dumps(t.get("input_schema") or t.get("inputSchema"), indent=1) + "\n```\n")
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(tools)} tools -> {args.out}")
    for t in sorted(tools, key=lambda t: t["name"]):
        print(" -", t["name"])


if __name__ == "__main__":
    main()
